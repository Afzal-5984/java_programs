//conditional operators:
//(<,>,==,!=,>=,<=)
public class Conditional {
	public static void main (String[] args){
	int a = 2;
	int b = 2;
	boolean b1 = (a>b);
	System.out.println(b1);//false
	System.out.println(a<b);//false
	System.out.println(a>b);//false
	System.out.println(a<=b);//true
	System.out.println(a>=b);//true
	System.out.println(a!=b);//false
	System.out.println(a==b);//true
	}
}
