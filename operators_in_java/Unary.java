//unary operators :
//(a+=,a-=,a*=,a/=,a%=).

public class Unary {
	public static void main (String[] args){
			int a = 6;
			int b = 6;
			int c = 6;
			int d = 6;
			a+= 1;
			b-= 1;
			c*= 1;
			d/= 1;
			System.out.println(a);//7
			System.out.println(b);//5
			System.out.println(c);//6
			System.out.println(d);//6
	}
}