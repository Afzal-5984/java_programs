//Arithmatic operators:-
//(+,-,*,/,%)
	public class Arithmatic {
        public static void main(String[] args){

		int a = 2 ;
		int b = 3 ;
		//float a = 2.0f ;
		//int b = 3 ;
		//double a = 2 ;
		//int b = 3 ;
	System.out.println(a+b);//5.0,5
	System.out.println(a-b);//-1.0,-1
	System.out.println(a*b);//6.0,6
	System.out.println(a/b);//0.6666666666666666,0
	System.out.println(a%b);//2.0,2
	System.out.println('A'+1);//66,66
	System.out.println('A'+'A');//130,130
	System.out.println((char)('A'+'A'));//?,?
	System.out.println((char)('A'+1));//B ,B
	}
}
